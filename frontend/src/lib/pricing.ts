// Цена подписки и скидка для тех, кому отказано в размещении в каталоге.
//
// Отказ в каталоге — не «до свидания»: человек продолжает вести своих клиентов
// на платформе, просто его карточки нет в общей выдаче. Поэтому подписка для
// него дешевле, и это единственное место, где обе цены заданы.

export const PRO_PRICE_RUB = 990;
export const PRO_DISCOUNT_PRICE_RUB = 600;

/** Кому положена скидка: отказ по каталогу вынесен модерацией. */
export const hasCatalogDecline = (status: string | null | undefined) => status === "declined";

/** Что человек заплатит за месяц PRO. */
export const proPriceFor = (status: string | null | undefined) =>
  hasCatalogDecline(status) ? PRO_DISCOUNT_PRICE_RUB : PRO_PRICE_RUB;

/** Единственная формулировка отказа — её видит и кабинет, и уведомление. */
export const CATALOG_DECLINE_TEXT =
  "К сожалению, ваше образование не подходит для размещения в каталоге. Но вы можете продолжать пользоваться платформой: ваши клиенты увидят профиль и заполненную анкету.";
