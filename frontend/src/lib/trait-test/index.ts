export type ScaleResult = {
  code: string;
  title: string;
  stateTitle: string;
  percent: number;
  state: State;
  details: { what: string; how: string; help: string };
};

export function stateFromPercent(pct: number): State {
  if (pct > HIGH_THRESHOLD) return "high";
  if (pct < LOW_THRESHOLD) return "low";
  return "mid";
}

/** Балл 0..3 с учётом reverse и веса вопроса, проценты — доля от максимума по шкале. */
export function scoreAnswers(questions: Question[], answers: Record<string, number>): ScaleResult[] {
  const sum: Record<string, number> = {};
  const max: Record<string, number> = {};

  for (const q of questions) {
    const raw = answers[q.id];
    if (raw === undefined) continue;
    let v = Math.max(0, Math.min(3, Math.round(raw)));
    if (q.reverse) v = 3 - v;
    const weight = q.weight > 0 ? q.weight : 1;
    for (const code of q.keys) {
      if (!code) continue;
      sum[code] = (sum[code] ?? 0) + v * weight;
      max[code] = (max[code] ?? 0) + 3 * weight;
    }
  }

  const results: ScaleResult[] = SCALES.map((s) => {
    const m = max[s.code] ?? 0;
    const percent = m > 0 ? Math.min(100, Math.max(0, Math.round(((sum[s.code] ?? 0) / m) * 100))) : 0;
    const state = stateFromPercent(percent);
    const block = SCALE_REPORTS[s.code]?.[state];
    return {
      code: s.code,
      title: s.title,
      stateTitle: block?.title || s.title,
      percent,
      state,
      details: {
        what: block?.what || "Описание для этой шкалы пока не заполнено.",
        how: block?.how || "—",
        help: block?.help || "—",
      },
    };
  });

  return results.sort((a, b) => b.percent - a.percent);
}

/** Восстановление результата из сохранённых процентов — тексты не храним. */
export function resultsFromPercents(percents: Record<string, number>): ScaleResult[] {
  return SCALES.map((s) => {
    const percent = Math.min(100, Math.max(0, Math.round(percents[s.code] ?? 0)));
    const state = stateFromPercent(percent);
    const block = SCALE_REPORTS[s.code]?.[state];
    return {
      code: s.code,
      title: s.title,
      stateTitle: block?.title || s.title,
      percent,
      state,
      details: {
        what: block?.what || "Описание для этой шкалы пока не заполнено.",
        how: block?.how || "—",
        help: block?.help || "—",
      },
    };
  }).sort((a, b) => b.percent - a.percent);
}

