function hash32(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/** xorshift32: тот же принцип, что в исходном плагине — стабильный порядок по seed. */
function seededShuffle<T>(arr: T[], seed: number): T[] {
  const out = arr.slice();
  let x = seed || 1;
  for (let i = out.length - 1; i > 0; i--) {
    x ^= (x << 13) >>> 0;
    x = x >>> 0;
    x ^= x >>> 17;
    x ^= (x << 5) >>> 0;
    x = x >>> 0;
    const j = x % (i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** Набор вопросов под версию: поровну от каждой шкалы, порядок зависит от seed. */
export function pickQuestions(variant: Variant, seed: string): Question[] {
  const seedInt = hash32(seed);
  const buckets = new Map<string, Question[]>();
  for (const s of SCALES) buckets.set(s.code, []);
  for (const q of QUESTIONS) {
    const primary = q.keys[0] ?? "";
    buckets.get(primary)?.push(q);
  }
  for (const [code, list] of buckets) buckets.set(code, seededShuffle(list, (seedInt ^ hash32(code)) >>> 0));

  const per = Math.floor(variant / SCALES.length);
  const picked: Question[] = [];
  for (const s of SCALES) {
    const list = buckets.get(s.code) ?? [];
    picked.push(...list.slice(0, per));
    buckets.set(s.code, list.slice(per));
  }
  const remain = variant - picked.length;
  if (remain > 0) {
    const pool: Question[] = [];
    for (const s of SCALES) pool.push(...(buckets.get(s.code) ?? []));
    picked.push(...seededShuffle(pool, (seedInt ^ 0x9e3779b9) >>> 0).slice(0, remain));
  }
  return seededShuffle(picked, (seedInt ^ 0x5bf03635) >>> 0);
}

