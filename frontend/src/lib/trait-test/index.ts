const CONFLICT_PAIRS: [string, string][] = [
  ["DEPENDENT", "AVOIDANT"],
  ["OCPD", "PARANOID"],
  ["NARCISSISTIC", "BORDERLINE"],
  ["SCHIZOID", "HISTRIONIC"],
];

function median(vals: number[]): number {
  const s = vals.slice().sort((a, b) => a - b);
  if (!s.length) return 0;
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
}

export function profilePattern(scoreMap: Record<string, number>): Pattern {
  const vals = Object.values(scoreMap);
  if (!vals.length) return "flat";
  const mean = vals.reduce((a, b) => a + b, 0) / vals.length;
  const std = Math.sqrt(vals.reduce((acc, v) => acc + (v - mean) ** 2, 0) / vals.length);
  const highCount = vals.filter((v) => v > HIGH_THRESHOLD).length;
  if (highCount === 0 && std < 8.5) return "flat";
  const max = Math.max(...vals);
  if (max > HIGH_THRESHOLD && max - median(vals) >= 15) return "spiky";
  for (const [a, b] of CONFLICT_PAIRS) {
    if ((scoreMap[a] ?? 0) > HIGH_THRESHOLD && (scoreMap[b] ?? 0) > HIGH_THRESHOLD) return "conflicted";
  }
  return "mixed";
}

/** Механизмы: веса шкал складываются с коэффициентом выраженности, топ-8. */
export function mechanismsFromScales(scoreMap: Record<string, number>): { tag: string; weight: number; plain: string }[] {
  const acc: Record<string, number> = {};
  const plain: Record<string, string> = {};

  for (const [code, pct] of Object.entries(scoreMap)) {
    const state = stateFromPercent(pct);
    const k = state === "high" ? 1 : state === "mid" ? 0.55 : 0.15;
    for (const m of MECHANISMS[code] ?? []) {
      if (!m.tag || m.w <= 0) continue;
      acc[m.tag] = (acc[m.tag] ?? 0) + m.w * k;
      if (!plain[m.tag] && m.plain_ru) plain[m.tag] = m.plain_ru;
    }
  }

  const values = Object.values(acc);
  if (!values.length) return [];
  const max = Math.max(...values) || 1;
  return Object.entries(acc)
    .map(([tag, w]) => ({ tag, weight: Math.round((w / max) * 1000) / 1000, plain: plain[tag] ?? tag }))
    .sort((a, b) => b.weight - a.weight)
    .slice(0, 8);
}

function profileTitle(results: ScaleResult[], scoreMap: Record<string, number>): string {
  const pa = results[0]?.percent ?? 0;
  const pb = results[1]?.percent ?? 0;
  const veryHigh = Object.values(scoreMap).filter((v) => v >= 80).length;
  if (veryHigh >= 7) return "Диффузная выраженность по всем шкалам";
  if (veryHigh >= 5) return "Множественные выраженные паттерны";
  if (veryHigh >= 3) return `${veryHigh} выраженных паттерна`;
  if (veryHigh === 2 && pa >= 80 && pb >= 80) return "Два устойчиво выраженных паттерна";
  if (veryHigh === 1 && pa >= 80) return "Один ведущий паттерн";
  if (pa > HIGH_THRESHOLD) return "Выраженная зона напряжения";
  return "Профиль личности";
}

