-- Бесплатное размещение в каталоге: деньги переезжают с места в выдаче на
-- подтверждение записи и клиентов сверх бесплатных трёх.
--
-- Миграция аддитивная: старый код с этими колонками работает как раньше,
-- откат образа базу не ломает.

-- Разовый пробный PRO по первой заявке из каталога (30 дней). NULL — не брали.
ALTER TABLE "User" ADD COLUMN "catalogTrialAt" TIMESTAMP(3);

-- Карточка из неподтверждённой заявки. Место в бесплатном лимите не занимает.
-- Всё, что заведено до релиза, подтверждено по определению: эти люди уже в
-- практике, и разом объявить их «ожидающими» нельзя.
ALTER TABLE "Client" ADD COLUMN "pending" BOOLEAN NOT NULL DEFAULT false;

-- Порядок в каталоге считает заходы за месяц.
CREATE INDEX "Visit_userId_createdAt_idx" ON "Visit"("userId", "createdAt");
