-- Подтверждение записи специалистом.
-- Аддитивно: колонка nullable, старый код её просто не замечает.
ALTER TABLE "Appointment" ADD COLUMN "confirmedAt" TIMESTAMP(3);

-- Всё, что записано до этого релиза, считается подтверждённым: иначе у каждого
-- специалиста разом всплывёт очередь «ждут подтверждения» из старых встреч.
UPDATE "Appointment" SET "confirmedAt" = "createdAt";
